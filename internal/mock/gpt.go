package mock

import (
	"context"
	"encoding/json"
	"fmt"

	"github.com/sashabaranov/go-openai"
)

// GPTClient is a fake OpenAI client for local development. It returns a placeholder card for any word.
type GPTClient struct{}

func (GPTClient) CreateChatCompletion(
	_ context.Context,
	request openai.ChatCompletionRequest,
) (openai.ChatCompletionResponse, error) {
	var req struct {
		Word string `json:"word"`
	}
	if len(request.Messages) > 0 {
		_ = json.Unmarshal([]byte(request.Messages[len(request.Messages)-1].Content), &req)
	}

	content, err := json.Marshal(Card(req.Word))
	if err != nil {
		return openai.ChatCompletionResponse{}, err
	}

	return openai.ChatCompletionResponse{
		Choices: []openai.ChatCompletionChoice{
			{
				Message:      openai.ChatCompletionMessage{Content: string(content)},
				FinishReason: openai.FinishReasonStop,
			},
		},
	}, nil
}

// Card returns the placeholder card the mock generates for word.
func Card(word string) map[string]any {
	return map[string]any{
		"word":                word,
		"plural":              word + "s",
		"translations":        []map[string]any{{"pos": "Noun", "translations": []string{"mock " + word}}},
		"article":             "der",
		"gender":              "m.",
		"transcription":       "/mɒk/",
		"context":             fmt.Sprintf("This is a mock card for %q.", word),
		"context_translation": fmt.Sprintf("Mock translation for %q.", word),
		"definition":          "Generated by the OpenAI mock (mockopenai: true).",
	}
}
