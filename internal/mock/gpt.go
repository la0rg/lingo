package mock

import (
	"context"
	"encoding/json"
	"fmt"

	"github.com/openai/openai-go/v3"
	"github.com/openai/openai-go/v3/option"
)

// GPTClient is a fake OpenAI client for local development (mockopenai: true).
// It returns a placeholder card for any word.
type GPTClient struct{}

func (GPTClient) New(
	_ context.Context, body openai.ChatCompletionNewParams, _ ...option.RequestOption,
) (*openai.ChatCompletion, error) {
	var req struct {
		Word string `json:"word"`
	}
	for _, msg := range body.Messages {
		if msg.OfUser != nil {
			_ = json.Unmarshal([]byte(msg.OfUser.Content.OfString.Value), &req)
		}
	}

	content, err := json.Marshal(Card(req.Word))
	if err != nil {
		return nil, err
	}

	return &openai.ChatCompletion{
		Model: "mock",
		Choices: []openai.ChatCompletionChoice{{
			Message:      openai.ChatCompletionMessage{Content: string(content)},
			FinishReason: "stop",
		}},
	}, nil
}

// Card returns the placeholder card the mock generates for word.
func Card(word string) map[string]any {
	return map[string]any{
		"word":                word,
		"plural":              word + "s",
		"translations":        []map[string]any{{"pos": "Noun", "translations": []string{"mock " + word}}},
		"article":             "der",
		"gender":              "m.",
		"transcription":       "/mɒk/",
		"context":             fmt.Sprintf("This is a mock card for %q.", word),
		"context_translation": fmt.Sprintf("Mock translation for %q.", word),
		"definition":          "Generated by the OpenAI mock (mockopenai: true).",
	}
}
